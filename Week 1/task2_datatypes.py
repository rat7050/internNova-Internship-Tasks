"""Write a Python program that:

Declares variables of different data types:
Integer
Float
String
Boolean
Print each variable along with its data type using type()."""

# Different data types

age = 20
percentage = 85.5
name = "Ratnesh Kumar"
is_student = True

# Display values and their data types

print("Age:", age, "| Type:", type(age))
print("Percentage:", percentage, "| Type:", type(percentage))
print("Name:", name, "| Type:", type(name))
print("Student:", is_student, "| Type:", type(is_student))